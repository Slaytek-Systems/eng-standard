// Every config value eng copies into the AGENTS.md block (project.name, project.description, a review rule and
// agents.skills_dir) must be one line (Core task p57cxn78pw2v6qb0n5daderzyd8jn9j0). A line break of any kind could carry a
// signed marker pair into the block, and the next eng sync would refuse the file it wrote. Config validation refuses such
// a value before any write, with one line naming the key and never the raw value.
import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync, execSync } from 'node:child_process';
import YAML from 'yaml';
import { agentsBlockErrors } from '../lib/render.mjs';
import { dirValueErrors } from '../lib/verification.mjs';
process.env.XDG_CACHE_HOME = fs.mkdtempSync(path.join(process.env.ENG_TMP ?? os.tmpdir(), 'eng-xdg-'));
process.on('exit', () => fs.rmSync(process.env.XDG_CACHE_HOME, { recursive: true, force: true }));

const ENG = path.resolve(new URL('../bin/eng.mjs', import.meta.url).pathname);
const PKG = path.dirname(path.dirname(ENG));
const scratch = [];
after(() => scratch.forEach(d => fs.rmSync(d, { recursive: true, force: true })));

const SIG = '<!-- GENERATED by eng from eng.config.yml. Do not edit; edit the config and run `eng sync`. -->';
// Every line break a reader may honour: LF, CR, VT, FF, the file, group and record separators, NEL, U+2028, U+2029.
const BREAKS = ['\n', '\r', '\r\n', '\v', '\f', '\x1c', '\x1d', '\x1e', '\x85', '\u2028', '\u2029'];
// The task's case: a value holding a signed begin/end pair.
const PAIR = `x\n<!-- eng:begin -->\n${SIG}\n<!-- eng:end -->\ny`;
const RAW = /[\n\r\v\f\x1c-\x1e\x85\u2028\u2029]/;
// [key, set(cfg, value), a value of that key that renders fine]
const KEYS = [
  ['project.name', (c, v) => { c.project.name = v; }, 'my-app'],
  ['project.description', (c, v) => { c.project.description = v; }, 'A web app.'],
  ['agents.rules[0].rule', (c, v) => { c.agents.rules = [{ rule: v, enforced_by: 'review', why: 'judgment' }]; }, 'Deploys run by hand'],
  ['agents.skills_dir', (c, v) => { c.agents.skills_dir = v; }, 'tools/skills'],
];
const template = () => YAML.parse(fs.readFileSync(path.join(PKG, 'templates/eng.config.yml'), 'utf8'));
const errsOf = c => [...dirValueErrors(c), ...agentsBlockErrors(c)];

test('config validation refuses a rendered value with a line break of any kind, naming the key', () => {
  for (const [key, set, ok] of KEYS) {
    for (const br of BREAKS) {
      for (const v of [`${ok}${br}more`, `${ok}${br}`]) {
        const c = template(); set(c, v);
        const errs = errsOf(c).filter(e => e.startsWith(key));
        assert.equal(errs.length, 1, `${key} ${JSON.stringify(v)}: ${JSON.stringify(errsOf(c))}`);
        assert.doesNotMatch(errs[0], RAW, `${key} ${JSON.stringify(v)}: the error is one line`);
      }
    }
    const c = template(); set(c, ok);
    assert.deepEqual(errsOf(c), [], `${key} ${ok} is fine`);
  }
});

test('config validation refuses a project.name that holds a marker, and keeps a bare -->', () => {
  for (const v of [PAIR, '<!-- eng:end -->', 'app <!-- x']) {
    const c = template(); c.project.name = v;
    assert.equal(errsOf(c).filter(e => e.startsWith('project.name')).length, 1, JSON.stringify(v));
  }
  const c = template(); c.project.name = 'draft --> app';
  assert.deepEqual(errsOf(c), []);
});

function repo() {
  const parent = fs.mkdtempSync(path.join(process.env.ENG_TMP ?? os.tmpdir(), 'eng-rendered-')); scratch.push(parent);
  const dir = path.join(parent, 'repo'); fs.mkdirSync(dir);
  const git = c => execSync(`git ${c}`, { cwd: dir, stdio: 'pipe', encoding: 'utf8' }).trim();
  git('init -q -b main'); git('config user.email t@t'); git('config user.name t');
  const c = template(); c.gates.required = []; c.agents.rules = []; c.constraints = { rules: [] };
  fs.writeFileSync(path.join(dir, 'eng.config.yml'), YAML.stringify(c));
  fs.writeFileSync(path.join(dir, 'README.md'), 'x\n');
  git('add -A'); git('commit -qm base');
  const eng = args => spawnSync(process.execPath, [ENG, ...args], { cwd: dir, encoding: 'utf8', timeout: 120_000, env: { ...process.env, ENG_STANDARD_SOURCE: PKG } });
  const s = eng(['sync']); assert.equal(s.status, 0, s.stdout + s.stderr);
  git('add -A'); git('commit -qm synced');
  return { dir, eng, base: c };
}
function shot(dir) {
  const s = { parent: fs.readdirSync(path.dirname(dir)).sort().join('\n') };
  const walk = rel => { const abs = path.join(dir, rel); const st = fs.lstatSync(abs); if (st.isDirectory()) { s[rel] = 'dir'; for (const n of fs.readdirSync(abs).sort()) if (!(rel === '' && n === '.git')) walk(path.join(rel, n)); } else s[rel] = st.isSymbolicLink() ? `link:${fs.readlinkSync(abs)}` : fs.readFileSync(abs, 'utf8'); };
  walk('');
  return s;
}

test('eng sync, sync --check and init refuse a rendered value with a line break: exit 1, one line naming the key, no raw value, nothing written', () => {
  const r = repo();
  for (const [key, set, ok] of KEYS) {
    for (const v of [PAIR, `${ok}\u2028<!-- eng:end -->`, `${ok}\rmore`]) {
      const c = structuredClone(r.base); set(c, v);
      fs.writeFileSync(path.join(r.dir, 'eng.config.yml'), YAML.stringify(c));
      const before = shot(r.dir);
      for (const args of [['sync'], ['sync', '--check'], ['init']]) {
        const res = r.eng(args), why = `${key} ${JSON.stringify(v)}: eng ${args.join(' ')}`, all = res.stdout + res.stderr;
        assert.equal(res.status, 1, `${why} refuses: ${all.slice(-1500)}`);
        assert.match(res.stderr, /config invalid/, why);
        const lines = res.stderr.split('\n').filter(l => l.includes(key));
        assert.equal(lines.length, 1, `${why}: one line names the key: ${JSON.stringify(res.stderr)}`);
        assert.doesNotMatch(all.replaceAll('\n', ''), RAW, `${why}: no raw line break from the value`);
        assert.ok(!all.includes(SIG), `${why}: the signed line is never echoed`);
        assert.deepEqual(shot(r.dir), before, `${why} wrote nothing`);
      }
    }
  }
  // A one-line value still syncs, and the next sync and sync --check accept what it wrote.
  const c = structuredClone(r.base); c.project.name = 'draft --> app'; c.project.description = 'One line.';
  fs.writeFileSync(path.join(r.dir, 'eng.config.yml'), YAML.stringify(c));
  for (const args of [['sync'], ['sync'], ['sync', '--check']]) { const res = r.eng(args); assert.equal(res.status, 0, res.stdout + res.stderr); }
});
